export function maskCells() {
  const cells = [];
  for (let y = 0; y < YA_MASK.length; y += 1) {
    for (let x = 0; x < YA_MASK.length; x += 1) {
      if (YA_MASK[y][x] === '#') cells.push(y * YA_MASK.length + x);
    }
  }
  return cells;
}
